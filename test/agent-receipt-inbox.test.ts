import type { FastifyInstance } from 'fastify'
import { beforeAll, afterAll, expect, it } from 'vitest'
import { makeApp, makeBusiness, authed } from './helpers.ts'
import { prisma } from '../src/db.ts'
let app: FastifyInstance
beforeAll(async()=>{app=await makeApp()})
afterAll(async()=>{await app.close();await prisma.$disconnect()})
async function setup(){
  const b=await makeBusiness(app), owner=authed(b.ownerToken)
  const key=(await app.inject({method:'POST',url:'/rms/agent/keys',headers:owner,payload:{label:'inbox'}})).json().key
  await prisma.brand.create({data:{businessId:b.businessId,name:'Second',sortOrder:1,colour:'#123456',softColour:'#eeeeee'}})
  const brands=await prisma.brand.findMany({where:{businessId:b.businessId},orderBy:{sortOrder:'asc'}})
  for(const [telegramUserId,role] of [['111','OWNER'],['222','BOOKKEEPER'],['333','VIEWER']]) await app.inject({method:'POST',url:'/rms/agent/users',headers:owner,payload:{telegramUserId,role,name:role}})
  const call=(method:any,url:string,payload?:any,user='111')=>app.inject({method,url,payload,headers:{authorization:`Bearer ${key}`,'x-telegram-user':user}})
  const ok=async(method:any,url:string,payload?:any,user='111')=>{const r=await call(method,url,payload,user);expect(r.statusCode,r.body).toBe(200);return r.json()}
  let n=0
  const upload=async()=> (await ok('POST','/agent/receipts',{imageBase64:Buffer.from(`${b.businessId}:${n++}`).toString('base64'),deferProcessing:true})).receipt.id
  const read=(id:string,extra:any={})=>ok('PATCH',`/agent/receipts/${id}/extraction`,{vendor:'Supplier',receiptDate:'2026-10-10',receiptNo:`INV-${id}`,totalSen:1000,extracted:{lines:[{name:'Recurring fries',qty:1,unit_price_rm:10,amount_rm:10}]},...extra})
  return {b:{...b,brands:{food:brands[0]!.id}},call,ok,upload,read}
}
it('persists actor-only auto stash, queues work and suppresses interruption without spending',async()=>{
  const s=await setup()
  await s.ok('PATCH','/agent/inbox/settings',{autoStash:true})
  expect((await s.ok('GET','/agent/inbox/settings','', '222')).autoStash).toBe(false)
  const id=await s.upload(),r=await prisma.receiptDocument.findUniqueOrThrow({where:{id},include:{job:true,image:true}})
  expect(r.status).toBe('SKIPPED');expect(r.job?.status).toBe('PENDING');expect(r.image).not.toBeNull()
  expect((await s.ok('GET',`/agent/receipts/${id}/telegram-context`)).suppressNotification).toBe(true)
  expect(await prisma.expense.count({where:{businessId:s.b.businessId}})).toBe(0)
  expect((await s.call('PATCH','/agent/inbox/settings',{autoStash:true},'333')).statusCode).toBe(403)
  await s.ok('PATCH','/agent/inbox/settings',{autoStash:false})
  expect((await s.ok('GET','/agent/inbox/settings')).autoStash).toBe(false)
})
it('number selection is durable, actor/business isolated and flags distinguish processing from ready',async()=>{
  const s=await setup(),other=await setup(),id=await s.upload();await s.read(id)
  const list=await s.ok('POST','/agent/inbox/review',{order:'flags'})
  expect(list.entries[0]).toMatchObject({id,number:1,ready:false});expect(list.entries[0].flags).toContain('Cross-check pending')
  expect((await s.ok('POST','/agent/inbox/select',{listId:list.listId,number:1})).receiptId).toBe(id)
  expect((await s.call('POST','/agent/inbox/select',{listId:list.listId,number:1},'222')).statusCode).toBe(404)
  expect((await other.call('POST','/agent/inbox/select',{listId:list.listId,number:1})).statusCode).toBe(404)
  await s.ok('POST',`/agent/receipts/${id}/defer`,{})
  expect((await s.ok('POST','/agent/inbox/review',{})).entries[0].flags).toContain('Revisit later')
})
it('cross-checks split expenses and candidate papers without deciding duplication or posting',async()=>{
  const s=await setup(),id=await s.upload();await s.read(id,{receiptNo:'SHARED-INVOICE',totalSen:1000})
  for(const amountSen of [400,600]) await app.inject({method:'POST',url:'/rms/expenses',headers:authed(s.b.ownerToken),payload:{businessDate:'2026-10-10',amountSen,category:'RAW_MATERIALS',paidBy:'STALL_FUNDS',brandId:s.b.brands.food,foodSplitPct:100,description:'historical split',vendor:'Supplier',receiptNo:'SHARED-INVOICE'}})
  const checks=await s.ok('POST',`/agent/receipts/${id}/checks`,{})
  expect(checks.matches).toHaveLength(2);expect(checks.matches.every((m:any)=>m.why.includes('rows with this receipt number add up to the total'))).toBe(true)
  const second=await s.upload();await s.read(second,{receiptNo:'SHARED-INVOICE'})
  expect((await s.ok('POST',`/agent/receipts/${second}/checks`,{})).duplicates.some((d:any)=>d.id===id)).toBe(true)
  expect((await s.ok('POST','/agent/inbox/review',{})).entries.find((r:any)=>r.id===id).flags).toContain('Existing Vista transactions — review linking')
  expect(await prisma.expense.count({where:{businessId:s.b.businessId}})).toBe(2)
})
it('learns confirmed item category/brand across actors but never overrides an edited draft',async()=>{
  const s=await setup()
  const brands=await prisma.brand.findMany({where:{businessId:s.b.businessId},orderBy:{sortOrder:'asc'}})
  const brandId=brands[1]!.id
  const posted=await app.inject({method:'POST',url:'/rms/expenses',headers:authed(s.b.ownerToken),payload:{businessDate:'2026-10-10',amountSen:1000,category:'PACKAGING',paidBy:'STALL_FUNDS',brandId,foodSplitPct:100,description:'Confirmed',items:[{name:'Recurring fries',quantityMilli:1000,unitPriceSen:1000}]}})
  expect(posted.statusCode,posted.body).toBe(200)
  const id=await s.upload();await s.read(id)
  const form=await s.ok('GET',`/agent/receipts/${id}/form`,undefined,'222')
  expect(form.form.lines[0]).toMatchObject({brand:brandId,category:'PACKAGING'});expect(form.form.suggestions[0].source).toBe('confirmed Vista entries')
  await s.ok('PATCH',`/agent/receipts/${id}/form`,{version:0,field:'category',value:'OPERATIONS'},'222')
  expect((await s.ok('GET',`/agent/receipts/${id}/form`,undefined,'222')).form.lines[0].category).toBe('OPERATIONS')
})
it('provides bank custom fields, requires purpose and rejects incoming/unknown as expenses',async()=>{
  const s=await setup(),id=await s.upload()
  await s.read(id,{extracted:{document_type:'bank_screenshot',transaction_direction:'unknown',lines:[]}})
  let form=await s.ok('GET',`/agent/receipts/${id}/form`)
  expect(form.form.lines[0]).toMatchObject({custom:true,amountSen:1000});expect(form.form.paidBy).toBe('STALL_FUNDS')
  expect((await s.call('POST',`/agent/receipts/${id}/form/preview`,{})).statusCode).toBe(400)
  await s.ok('PATCH',`/agent/receipts/${id}/extraction`,{extracted:{transaction_direction:'outgoing'}})
  expect((await s.call('POST',`/agent/receipts/${id}/form/preview`,{})).body).toContain('purpose')
  await s.ok('PATCH',`/agent/receipts/${id}/extraction`,{extracted:{purpose:'Supplier transfer'}})
  form=await s.ok('GET',`/agent/receipts/${id}/form`)
  expect(form.form.lines[0].name).toBe('Supplier transfer')
  const preview=await s.ok('POST',`/agent/receipts/${id}/form/preview`,{})
  expect(preview.entriesTotalSen).toBe(1000)
  await s.ok('PATCH',`/agent/receipts/${id}/extraction`,{extracted:{transaction_direction:'incoming'}})
  expect((await s.call('POST',`/agent/receipts/${id}/form/post`,{confirmationId:preview.confirmationId})).statusCode).toBe(409)
  expect(await prisma.expense.count({where:{businessId:s.b.businessId}})).toBe(0)
})
it('recovers exact confirmation result, advances sequentially only after all items and never reposts',async()=>{
  const s=await setup(),first=await s.upload(),second=await s.upload();await s.read(first);await s.read(second)
  const list=await s.ok('POST','/agent/inbox/review',{sequential:true})
  await s.ok('POST','/agent/inbox/select',{listId:list.listId,number:1})
  expect((await s.ok('POST','/agent/inbox/next',{receiptId:first})).next).toBeNull()
  const path=`/agent/receipts/${first}/form`,p=await s.ok('POST',path+'/preview',{})
  expect((await s.ok('GET',path+'/confirmations/'+p.confirmationId)).state).toBe('unconfirmed')
  const saved=await s.ok('POST',path+'/post',{confirmationId:p.confirmationId})
  expect(saved.annotation.pending).toBe(true)
  const recovered=await s.ok('GET',path+'/confirmations/'+p.confirmationId)
  expect(recovered.state).toBe('posted');expect(recovered.expenseIds).toEqual(saved.expenseIds)
  expect((await s.call('GET',path+'/confirmations/'+p.confirmationId,undefined,'222')).statusCode).toBe(404)
  expect((await s.call('POST',path+'/post',{confirmationId:p.confirmationId})).statusCode).toBe(409)
  expect((await s.ok('POST','/agent/inbox/next',{receiptId:first})).next.receiptId).toBe(second)
  expect(await prisma.expense.count({where:{businessId:s.b.businessId}})).toBe(1)
})
it('auto-stash duplicate of fully booked paper stays flagged without another document or expense',async()=>{
  const s=await setup(),id=await s.upload();await s.read(id)
  const p=await s.ok('POST',`/agent/receipts/${id}/form/preview`,{})
  await s.ok('POST',`/agent/receipts/${id}/form/post`,{confirmationId:p.confirmationId})
  await s.ok('PATCH','/agent/inbox/settings',{autoStash:true})
  const duplicate=await s.ok('POST','/agent/receipts',{imageBase64:Buffer.from(`${s.b.businessId}:0`).toString('base64'),deferProcessing:true})
  expect(duplicate).toMatchObject({autoStash:true,duplicate:true,receipt:{id,status:'POSTED'}})
  const inbox=await s.ok('POST','/agent/inbox/review',{})
  expect(inbox.entries[0].id).toBe(id);expect(inbox.entries[0].flags.join(' ')).toContain('Same photo')
  expect(await prisma.receiptDocument.count({where:{businessId:s.b.businessId}})).toBe(1)
  expect(await prisma.expense.count({where:{businessId:s.b.businessId}})).toBe(1)
  await s.ok('POST',`/agent/receipts/${id}/duplicate-reviewed`,{})
  expect((await s.ok('POST','/agent/inbox/review',{})).entries).toHaveLength(0)
})
